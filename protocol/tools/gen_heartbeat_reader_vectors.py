"""Generate protocol/vectors/heartbeat-readers.json: what a reader of heartbeats takes
from a later writer. Each document fails or passes this minor's writer schema as
`writerSchema` says, and a reader accepts every one (README.md > Versioning). Usage::

    python3 protocol/tools/gen_heartbeat_reader_vectors.py protocol/vectors/heartbeat-readers.json
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROTOCOL = open(os.path.join(HERE, "..", "VERSION"), encoding="utf-8").read().strip()
base = json.load(open(os.path.join(HERE, "..", "examples", "heartbeat.request.json"), encoding="utf-8"))

cases = [
    {"name": "an unknown top-level member", "document": {**base, "laterMember": {"count": 1}}, "reader": "accepted", "writerSchema": False},
    {"name": "a new refusal", "document": {**base, "refusal": "later_refusal"}, "reader": "accepted", "writerSchema": False},
    {"name": "an unknown member in registration", "document": {**base, "registration": {**base.get("registration", {}), "laterMember": 1}}, "reader": "accepted", "writerSchema": False},
    {"name": "an unknown member in spool", "document": {**base, "spool": {**base["spool"], "laterMember": 1}}, "reader": "accepted", "writerSchema": False},
    {"name": "a later applyState", "document": {**base, "applyState": "later_state"}, "reader": "accepted", "writerSchema": False},
    {"name": "a new runCounters family", "document": {**base, "runCounters": {"passthrough": {}, "experiments": {"exp-rollout-1": 3}}}, "reader": "accepted", "writerSchema": True},
    {"name": "a new sdk.name", "document": {**base, "sdk": {**base["sdk"], "name": "agent-sdk-rust"}}, "reader": "accepted", "writerSchema": True},
]

with open(sys.argv[1], "w", encoding="utf-8") as out:
    json.dump({"$comment": "Generated by protocol/tools/gen_heartbeat_reader_vectors.py. Expected answers are written there by hand. See README.md > Versioning.", "protocol": PROTOCOL, "cases": cases}, out, indent=2, ensure_ascii=False)
    out.write("\n")
print(f"{len(cases)} cases -> {sys.argv[1]}")
